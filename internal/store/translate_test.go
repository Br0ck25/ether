package store

import "testing"

func TestTranslateDDL(t *testing.T) {
	cases := []struct{ in, want string }{
		{
			`CREATE TABLE q(id INTEGER PRIMARY KEY AUTOINCREMENT,channel TEXT NOT NULL,created INTEGER NOT NULL)`,
			`CREATE TABLE q(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,channel TEXT NOT NULL,created BIGINT NOT NULL)`,
		},
		{
			`CREATE TABLE l(id INTEGER PRIMARY KEY, token_hash TEXT UNIQUE NOT NULL)`,
			`CREATE TABLE l(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash TEXT UNIQUE NOT NULL)`,
		},
		{
			`CREATE TABLE s(id INTEGER PRIMARY KEY CHECK(id=1),value TEXT NOT NULL); INSERT INTO s(id)VALUES(1);`,
			`CREATE TABLE s(id BIGINT PRIMARY KEY CHECK(id=1),value TEXT NOT NULL); INSERT INTO s(id)VALUES(1);`,
		},
		{
			"CREATE TABLE s (\n  id INTEGER PRIMARY KEY CHECK (id = 1),\n  rules TEXT NOT NULL\n)",
			"CREATE TABLE s (\n  id BIGINT PRIMARY KEY CHECK (id = 1),\n  rules TEXT NOT NULL\n)",
		},
		{
			`CREATE TABLE m(rating_key INTEGER PRIMARY KEY,fingerprint BLOB NOT NULL,score REAL NOT NULL DEFAULT 0)`,
			`CREATE TABLE m(rating_key BIGINT PRIMARY KEY,fingerprint BYTEA NOT NULL,score DOUBLE PRECISION NOT NULL DEFAULT 0)`,
		},
		{
			`ALTER TABLE t ADD COLUMN adult integer NOT NULL DEFAULT 0;`,
			`ALTER TABLE t ADD COLUMN adult BIGINT NOT NULL DEFAULT 0;`,
		},
		{
			`CREATE INDEX w ON t(user_id, last_viewed_at DESC) WHERE view_offset_ns > 0;`,
			`CREATE INDEX w ON t(user_id, last_viewed_at DESC) WHERE view_offset_ns > 0;`,
		},
		{
			// Literals, identifiers and comments are left alone.
			`CREATE TABLE t(kind TEXT NOT NULL DEFAULT 'INTEGER REAL', "BLOB" INTEGER) -- INTEGER`,
			`CREATE TABLE t(kind TEXT NOT NULL DEFAULT 'INTEGER REAL', "BLOB" BIGINT) -- INTEGER`,
		},
		{
			`user_id INTEGER NOT NULL REFERENCES auth_users(id) ON DELETE CASCADE, integers_ok TEXT`,
			`user_id BIGINT NOT NULL REFERENCES auth_users(id) ON DELETE CASCADE, integers_ok TEXT`,
		},
		{
			// Columns named after types keep their names.
			"CREATE TABLE t(blob BLOB, real REAL,\n integer INTEGER, n INTEGER); SELECT CAST(x AS INTEGER)",
			"CREATE TABLE t(blob BYTEA, real DOUBLE PRECISION,\n integer BIGINT, n BIGINT); SELECT CAST(x AS BIGINT)",
		},
	}
	for _, c := range cases {
		if got := TranslateDDL(c.in); got != c.want {
			t.Errorf("TranslateDDL(%q)\n got %q\nwant %q", c.in, got, c.want)
		}
	}
}

func TestRegisterDialectOverride(t *testing.T) {
	regMu.Lock()
	saved := migrations
	migrations = nil
	regMu.Unlock()
	defer func() {
		regMu.Lock()
		migrations = saved
		regMu.Unlock()
	}()
	RegisterDialect("x", 1, Postgres, `CREATE TABLE x_pg(v JSONB)`)
	Register("x", 1, `CREATE TABLE x_t(v TEXT)`)
	Register("x", 2, `CREATE TABLE x_u(v INTEGER)`)
	ms := registered()
	if len(ms) != 2 {
		t.Fatalf("registered %d migrations, want 2", len(ms))
	}
	if got := ms[0].sqlFor(SQLite); got != `CREATE TABLE x_t(v TEXT)` {
		t.Fatalf("sqlite text = %q", got)
	}
	if got := ms[0].sqlFor(Postgres); got != `CREATE TABLE x_pg(v JSONB)` {
		t.Fatalf("postgres override = %q", got)
	}
	if got := ms[1].sqlFor(Postgres); got != `CREATE TABLE x_u(v BIGINT)` {
		t.Fatalf("postgres translation = %q", got)
	}
}
