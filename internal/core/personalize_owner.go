// Owner-facing personalization shapes (docs/owner-ui.md, "Viewers and
// personalization", "Home Designer", "Insights"). The personalization
// engine produces them; internal/admin serves them. JSON tags follow the
// API contract.

// TasteWeight is one named affinity, weight in -1..1.
type TasteWeight struct {
	Name   string  `json:"name"`
	Weight float64 `json:"weight"`
}

// TastePerson is an affinity for a cast or crew member.
type TastePerson struct {
	ID     int64   `json:"id"`
	Name   string  `json:"name"`
	Role   string  `json:"role"` // "director", "writer", "actor"
	Weight float64 `json:"weight"`
	Image  string  `json:"image,omitempty"` // browser-loadable URL
}

// TasteDecade is an affinity for a release decade (1990 = the 90s).
type TasteDecade struct {
	Decade int     `json:"decade"`
	Weight float64 `json:"weight"`
}

// TasteLanguage is an affinity for an original language (ISO 639-1).
type TasteLanguage struct {
	Code   string  `json:"code"`
	Weight float64 `json:"weight"`
}

// TasteHabits are a viewer's learned viewing habits.
type TasteHabits struct {
	WeeknightMinutes float64 `json:"weeknightMinutes"` // typical minutes watched on an active weeknight
	WeekendMinutes   float64 `json:"weekendMinutes"`   // typical minutes watched on an active weekend day
	PreferredDevice  string  `json:"preferredDevice"`  // DeviceTV, DeviceMobile, ... or ""
	BingeScore       float64 `json:"bingeScore"`       // 0..1: share of episodes watched in same-day runs of 3+
	RewatchScore     float64 `json:"rewatchScore"`     // 0..1: share of finished titles watched again
	PeakHours        []int   `json:"peakHours"`        // most common start hours (local), busiest first
}

// TasteOverride is an owner correction applied on top of the learned
// model: Kind "genre" (Value = genre name), "person" (Value = TMDB person
// id) or "keyword" (Value = keyword); Weight -1..1 replaces the learned
// weight.
type TasteOverride struct {
	Kind   string  `json:"kind"`
	Value  string  `json:"value"`
	Weight float64 `json:"weight"`
}

// TasteProfile is the explainable view of one viewer's taste model.
type TasteProfile struct {
	UserID     int64           `json:"userId"`
	UpdatedAt  time.Time       `json:"updatedAt"`
	Confidence float64         `json:"confidence"` // 0..1, grows with history
	Genres     []TasteWeight   `json:"genres"`
	People     []TastePerson   `json:"people"`
	Keywords   []TasteWeight   `json:"keywords"`
	Decades    []TasteDecade   `json:"decades"`
	Languages  []TasteLanguage `json:"languages"`
	Habits     TasteHabits     `json:"habits"`
	Overrides  []TasteOverride `json:"overrides"`
}

